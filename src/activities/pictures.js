// Colouring pictures (viewBox 0 0 200 200). `r` = fillable regions, `d` = decorations drawn on top.
// Region shapes: { t: 'rect'|'circle'|'ellipse'|'path'|'poly', ...attrs, tr?: transform }

const R = (x, y, width, height, rx = 0) => ({ t: 'rect', x, y, width, height, rx });
const C = (cx, cy, r) => ({ t: 'circle', cx, cy, r });
const E = (cx, cy, rx, ry, tr) => ({ t: 'ellipse', cx, cy, rx, ry, tr });
const P = (d, tr) => ({ t: 'path', d, tr });
const POLY = (points) => ({ t: 'poly', points });
const line = (d) => ({ t: 'path', d, fill: 'none' });
const dot = (cx, cy, r = 4) => ({ t: 'circle', cx, cy, r, fill: '#2b2350' });

const sky = R(0, 0, 200, 200);

const rays = Array.from({ length: 8 }, (_, i) => {
  const a = (i * Math.PI) / 4;
  const p = (ang, rad) => `${(100 + Math.cos(ang) * rad).toFixed(1)},${(100 + Math.sin(ang) * rad).toFixed(1)}`;
  return POLY(`${p(a - 0.18, 58)} ${p(a, 92)} ${p(a + 0.18, 58)}`);
});

const kente = (() => {
  const out = [];
  for (let row = 0; row < 4; row++)
    for (let col = 0; col < 4; col++) {
      const x = col * 50;
      const y = row * 50;
      if ((row + col) % 2 === 0) {
        out.push(R(x, y, 50, 14), R(x, y + 14, 50, 8), R(x, y + 22, 50, 14), R(x, y + 36, 50, 14));
      } else {
        out.push(R(x, y, 14, 50), R(x + 14, y, 8, 50), R(x + 22, y, 14, 50), R(x + 36, y, 14, 50));
      }
    }
  return out;
})();

const mandala = (() => {
  const out = [C(100, 100, 96)];
  for (let i = 0; i < 12; i++) out.push(E(100, 38, 13, 30, `rotate(${i * 30} 100 100)`));
  for (let i = 0; i < 8; i++) out.push(E(100, 62, 10, 22, `rotate(${i * 45 + 22.5} 100 100)`));
  out.push(C(100, 100, 26), C(100, 100, 13));
  return out;
})();

const city = (() => {
  const out = [sky, C(160, 36, 18), R(0, 170, 200, 30)];
  const b = [[8, 80, 36], [48, 50, 30], [82, 96, 34], [120, 64, 32], [156, 104, 38]];
  b.forEach(([x, y, w]) => out.push(R(x, y, w, 170 - y)));
  b.forEach(([x, y, w]) => {
    for (let wy = y + 10; wy < 160; wy += 18) for (let wx = x + 6; wx < x + w - 8; wx += 12) out.push(R(wx, wy, 7, 9, 1));
  });
  return out;
})();

